"""The traceability matrix of the spec's rule IDs and the tests that check them.

52-testing-strategy.md §3: "traceability matrix generated by a script that greps rule IDs".

    uv run python scripts/rule_matrix.py                 # print the matrix of every spec
    uv run python scripts/rule_matrix.py --check 15      # fail when a rule of spec 15 has no test
    uv run python scripts/rule_matrix.py --markdown      # the matrix as Markdown tables

A rule ID is up to three letters and a number (``C3``, ``S2``). The spec declares one as a bold
bullet, ``- **C3 Absorption:** ...``, or as the first cell of a table row, ``| S2 | ... |``
(15 §2 and §7). A test claims a rule by its name: ``test_C3_absorption``,
``test_C3_two_deadlines_expiring_together``, in any ``test_*.py`` under ``tests/python``, as a
function or as a method. IDs are told apart by their spec only through the number, so two specs
must not declare the same ID (the script says so).

``--check N`` (repeatable) is the gate CI runs: every ID declared by spec ``N`` needs at least one
test. A test named after an ID no spec declares is reported, since it is usually a typo.

Exit status: 0 when clean, 1 when a checked rule has no test (or a spec is missing), 2 when a
path does not exist.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SPECS = REPOSITORY_ROOT / "docs" / "spec"
DEFAULT_TESTS = REPOSITORY_ROOT / "tests" / "python"

RULE_ID = r"[A-Z]{1,3}[0-9]{1,3}"
BULLET = re.compile(rf"^\s*[-*]\s+\*\*(?P<id>{RULE_ID})\b[ :.]*(?P<title>[^*]*)")
TABLE_ROW = re.compile(rf"^\|\s*\*{{0,2}}(?P<id>{RULE_ID})\*{{0,2}}\s*\|\s*(?P<title>[^|]*)")
TEST_NAME = re.compile(rf"^test_(?P<id>{RULE_ID})(?:_|$)")
SPEC_NUMBER = re.compile(r"^(?P<number>[0-9]+)-")


def spec_number(path: Path) -> str | None:
    match = SPEC_NUMBER.match(path.name)
    return match.group("number") if match else None


def rules_in_specs(specs: Path) -> dict[str, dict[str, str]]:
    """``{spec number: {rule ID: title}}`` for every spec under ``specs``."""
    rules: dict[str, dict[str, str]] = defaultdict(dict)
    for path in sorted(specs.rglob("*.md")):
        number = spec_number(path)
        if number is None:
            continue
        in_fence = False
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
            if in_fence:
                continue
            match = BULLET.match(line) or TABLE_ROW.match(line)
            if match:
                rules[number].setdefault(match.group("id"), match.group("title").strip())
    return dict(rules)


def tests_by_rule(tests: Path) -> dict[str, list[str]]:
    """``{rule ID: ["file.py::test_name", ...]}`` from the names of the tests under ``tests``."""
    claimed: dict[str, list[str]] = defaultdict(list)
    for path in sorted(tests.rglob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
                continue
            match = TEST_NAME.match(node.name)
            if match:
                claimed[match.group("id")].append(
                    f"{path.relative_to(tests).as_posix()}::{node.name}"
                )
    return dict(claimed)


def duplicated_ids(rules: dict[str, dict[str, str]]) -> dict[str, list[str]]:
    """Rule IDs that more than one spec declares: a test name cannot tell them apart."""
    owners: dict[str, list[str]] = defaultdict(list)
    for number, ids in rules.items():
        for rule_id in ids:
            owners[rule_id].append(number)
    return {rule_id: numbers for rule_id, numbers in owners.items() if len(numbers) > 1}


def render(
    rules: dict[str, dict[str, str]], claimed: dict[str, list[str]], *, markdown: bool
) -> str:
    lines: list[str] = []
    for number in sorted(rules, key=int):
        if markdown:
            lines += [f"### Spec {number}", "", "| Rule | Tests | First |", "|---|---|---|"]
        else:
            lines.append(f"spec {number}")
        for rule_id, title in rules[number].items():
            tests = claimed.get(rule_id, [])
            first = tests[0] if tests else "MISSING"
            if markdown:
                lines.append(f"| {rule_id} {title} | {len(tests)} | `{first}` |")
            else:
                lines.append(f"  {rule_id:<5}{len(tests):>3} tests  {first}")
        lines.append("")
    return "\n".join(lines)


def check(
    rules: dict[str, dict[str, str]], claimed: dict[str, list[str]], numbers: Iterable[str]
) -> list[str]:
    """What is wrong for the gate: rules of the checked specs with no test, unknown specs."""
    problems: list[str] = []
    for number in numbers:
        if number not in rules:
            problems.append(f"spec {number} declares no rule IDs (is the number right?)")
            continue
        problems += [
            f"spec {number}: rule {rule_id} has no test; name one test_{rule_id}_<what it checks>"
            for rule_id in rules[number]
            if rule_id not in claimed
        ]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    parser.add_argument("--specs", type=Path, default=DEFAULT_SPECS, help="the spec directory")
    parser.add_argument("--tests", type=Path, default=DEFAULT_TESTS, help="the Python tests")
    parser.add_argument("--check", action="append", default=[], metavar="N", help="gate spec N")
    parser.add_argument("--markdown", action="store_true", help="print Markdown tables")
    args = parser.parse_args(argv)
    for path in (args.specs, args.tests):
        if not path.is_dir():
            print(f"rule_matrix: {path} is not a directory", file=sys.stderr)
            return 2
    rules = rules_in_specs(args.specs)
    claimed = tests_by_rule(args.tests)
    print(render(rules, claimed, markdown=args.markdown))
    declared = {rule_id for ids in rules.values() for rule_id in ids}
    for rule_id in sorted(set(claimed) - declared):
        print(
            f"rule_matrix: warning: {claimed[rule_id][0]} names rule {rule_id}, which no spec "
            "declares (a typo? declare it in the spec, or rename the test)",
            file=sys.stderr,
        )
    for rule_id, numbers in sorted(duplicated_ids(rules).items()):
        print(
            f"rule_matrix: warning: rule {rule_id} is declared by specs {', '.join(numbers)}; "
            "a test name cannot tell them apart",
            file=sys.stderr,
        )
    problems = check(rules, claimed, args.check)
    for problem in problems:
        print(f"rule_matrix: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
